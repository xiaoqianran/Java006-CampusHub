CREATE TABLE IF NOT EXISTS t_resource_category (
    resource_id BIGINT NOT NULL,
    category_id BIGINT NOT NULL,
    create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (resource_id, category_id)
);
