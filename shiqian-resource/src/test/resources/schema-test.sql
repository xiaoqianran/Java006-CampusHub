CREATE TABLE IF NOT EXISTS t_content_review_record (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    resource_id BIGINT,
    submitter_id BIGINT,
    reviewer_id BIGINT,
    review_type VARCHAR(20) NOT NULL,
    decision VARCHAR(30) NOT NULL,
    matched_words VARCHAR(1000),
    reason VARCHAR(500),
    content_title VARCHAR(200),
    create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_review_resource ON t_content_review_record(resource_id, create_time);
CREATE INDEX IF NOT EXISTS idx_review_type_decision ON t_content_review_record(review_type, decision, create_time);

