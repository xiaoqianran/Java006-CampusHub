CREATE TABLE IF NOT EXISTS t_resource (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    title VARCHAR(200) NOT NULL,
    description VARCHAR(1000) DEFAULT NULL,
    summary VARCHAR(500) DEFAULT NULL,
    content_markdown LONGTEXT DEFAULT NULL,
    content_type VARCHAR(30) DEFAULT 'ARTICLE',
    content_scene VARCHAR(30) NOT NULL DEFAULT 'SHARE',
    tags VARCHAR(500) DEFAULT NULL,
    external_source VARCHAR(50) DEFAULT NULL,
    external_id VARCHAR(128) DEFAULT NULL,
    category_id BIGINT DEFAULT NULL,
    file_url VARCHAR(500) DEFAULT NULL,
    file_size BIGINT NOT NULL DEFAULT 0,
    file_type VARCHAR(100) DEFAULT NULL,
    download_count INT NOT NULL DEFAULT 0,
    view_count INT NOT NULL DEFAULT 0,
    version INT NOT NULL DEFAULT 1,
    status TINYINT NOT NULL DEFAULT 0,
    review_reason VARCHAR(500) DEFAULT NULL,
    reviewer_id BIGINT DEFAULT NULL,
    review_time DATETIME DEFAULT NULL,
    offline_reason VARCHAR(500) DEFAULT NULL,
    published_time DATETIME DEFAULT NULL,
    create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted TINYINT NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_user_id ON t_resource(user_id);
CREATE UNIQUE INDEX IF NOT EXISTS uk_external_content ON t_resource(external_source, external_id);
CREATE INDEX IF NOT EXISTS idx_content_scene ON t_resource(content_scene);
CREATE INDEX IF NOT EXISTS idx_category_id ON t_resource(category_id);

-- 资源附件表（测试用）
CREATE TABLE IF NOT EXISTS t_resource_attachment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    resource_id BIGINT NOT NULL,
    file_name VARCHAR(255) NOT NULL,
    file_url VARCHAR(500) NOT NULL,
    file_size BIGINT DEFAULT 0,
    file_type VARCHAR(100),
    mime_type VARCHAR(100),
    asset_kind VARCHAR(30) DEFAULT 'FILE',
    usage_type VARCHAR(30) DEFAULT 'ATTACHMENT',
    sort_order INT DEFAULT 0,
    create_time DATETIME DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_resource_id ON t_resource_attachment(resource_id);

CREATE TABLE IF NOT EXISTS t_stored_object (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id CHAR(36) NOT NULL,
    owner_id BIGINT NOT NULL,
    resource_id BIGINT DEFAULT NULL,
    object_key VARCHAR(500) NOT NULL,
    original_name VARCHAR(255) NOT NULL,
    storage_provider VARCHAR(30) NOT NULL,
    bucket_name VARCHAR(100),
    file_size BIGINT NOT NULL,
    extension VARCHAR(20) NOT NULL,
    mime_type VARCHAR(100) NOT NULL,
    asset_kind VARCHAR(30) NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'TEMPORARY',
    create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_stored_object_public_id ON t_stored_object(public_id);
CREATE UNIQUE INDEX IF NOT EXISTS uk_stored_object_key ON t_stored_object(object_key);
CREATE INDEX IF NOT EXISTS idx_stored_object_owner_status ON t_stored_object(owner_id, status);
CREATE INDEX IF NOT EXISTS idx_stored_object_resource ON t_stored_object(resource_id, status);
CREATE INDEX IF NOT EXISTS idx_stored_object_cleanup ON t_stored_object(status, create_time);

CREATE TABLE IF NOT EXISTS t_user_storage_quota (
    owner_id BIGINT PRIMARY KEY,
    used_bytes BIGINT NOT NULL DEFAULT 0,
    update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS t_sensitive_word (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    word VARCHAR(100) NOT NULL,
    level TINYINT NOT NULL DEFAULT 2,
    status TINYINT NOT NULL DEFAULT 1,
    created_by BIGINT,
    create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted TINYINT NOT NULL DEFAULT 0
);
